package com.jetbrains.kmpapp.data.storage

/**
 * Пара «ключ → значение» для подсчёта реального объёма хранилища.
 *
 * Раньше экран «Данные и память» показывал приблизительные цифры, зашитые
 * в вёрстку («~2.2 МБ» карт, «~64 КБ» задач), потому что [PlatformStorage]
 * умел только читать по известному ключу и не мог перечислить содержимое.
 * Теперь платформа отдаёт все свои пары, и статистика считается по факту.
 */
data class StorageEntry(val key: String, val value: String) {
    /**
     * Размер записи в байтах: ключ + значение в UTF-8.
     *
     * Считаем именно UTF-8, а не длину строки: русские названия групп и
     * предметов занимают вдвое больше байт, чем символов, и подсчёт по
     * символам занижал объём расписаний примерно в два раза.
     */
    val sizeBytes: Long
        get() = (key.encodeToByteArray().size + value.encodeToByteArray().size).toLong()
}

/**
 * Перечисление содержимого хранилища — нужно для честной статистики.
 *
 * Android: SharedPreferences.all (или файлы fallback-каталога).
 * iOS: dictionaryRepresentation с фильтром по префиксу приложения —
 * в стандартных defaults лежат и системные ключи, их учитывать нельзя.
 */
expect fun PlatformStorage.allEntries(): List<StorageEntry>